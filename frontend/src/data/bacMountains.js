function normalizeMountainName(name) {
  return String(name || '')
    .replace(/\([^)]*\)/g, '')
    .replace(/\s+/g, '')
    .trim()
}

export const bacMountains = officialMountains.map((mountain, index) => ({
  id: `bac-${index + 1}`,
  canonicalName: normalizeMountainName(mountain.name),
  ...mountain,
}))

export function findBacMountainForRecord(record) {
  if (!record?.mountainName) return null

  const recordName = normalizeMountainName(record.mountainName)
  const elevation = Number(record.elevationMeter)
  const candidates = bacMountains.filter((mountain) => mountain.canonicalName === recordName)

  if (candidates.length === 0) return null
  if (candidates.length === 1 || !Number.isFinite(elevation)) return candidates[0]

  return [...candidates].sort(
    (first, second) =>
      Math.abs(first.elevationMeter - elevation) - Math.abs(second.elevationMeter - elevation),
  )[0]
}
